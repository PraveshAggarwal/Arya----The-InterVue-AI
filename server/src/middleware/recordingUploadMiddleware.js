const multer = require("multer");
const path = require("path");
const fs = require("fs");
const { randomUUID } = require("crypto");

const uploadDirectory = path.join(process.cwd(), "uploads", "interviews");
fs.mkdirSync(uploadDirectory, { recursive: true });

const storage = multer.diskStorage({
  destination: (_req, _file, cb) => cb(null, uploadDirectory),
  filename: (_req, file, cb) => {
    const extension = path.extname(file.originalname).toLowerCase() || ".webm";
    cb(null, `${randomUUID()}${extension}`);
  },
});

const normalizeRecordingMimeType = (file) => {
  const extension = path.extname(file.originalname || "").toLowerCase();
  if (extension === ".mp4") return "video/mp4";
  if (extension === ".ogg" || extension === ".ogv") return "video/ogg";
  return "video/webm";
};

const upload = multer({
  storage,
  fileFilter: (_req, file, cb) => {
    // Browser MediaRecorder implementations report different MIME values for
    // the same recording. The filename is generated by this application, so
    // accept it and use a stable playback type based on its extension.
    file.normalizedMimeType = normalizeRecordingMimeType(file);
    cb(null, true);
  },
  limits: {
    fileSize: Number(process.env.MAX_RECORDING_SIZE_MB || 250) * 1024 * 1024,
    files: 1,
  },
});

module.exports = upload;
